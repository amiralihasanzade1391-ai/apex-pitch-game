// Global locale state & subscribers
let currentLocale = "fa";
const listeners = new Set();

export function setLocale(locale) {
  if (strings[locale] && currentLocale !== locale) {
    currentLocale = locale;
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'fa' ? 'rtl' : 'ltr';
    listeners.forEach((listener) => listener(locale));
  }
}

export function toggleLocale() {
  setLocale(currentLocale === 'fa' ? 'en' : 'fa');
}

export function getLocale() {
  return currentLocale;
}

export function t(key, ...args) {
  const dict = strings[currentLocale] || strings.fa;
  const val = dict[key] ?? strings.fa[key];
  if (typeof val === 'function') {
    return val(...args);
  }
  return val ?? key;
}

export function useI18n() {
  const [locale, setLocalLocale] = useState(currentLocale);

  useEffect(() => {
    listeners.add(setLocalLocale);
    return () => listeners.delete(setLocalLocale);
  }, []);

  return {
    locale,
    t,
    setLocale,
    toggleLocale,
    isRTL: locale === 'fa',
  };
}

export default strings;
